#!/bin/bash
#
# Generates gitinfo.tex with \githash, \gittag and \gitdate used in colophon.tex.
# gitinfo.tex is not tracked by git; it is regenerated on every latexmk run
# (see .latexmkrc) and by the GitHub release workflow.
#
# If git is not available (e.g. source downloaded as ZIP, or git refusing
# to work inside a container), an existing gitinfo.tex is left untouched.

cd "$(dirname "$0")" || exit 0

if ! git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    echo "gitinfo.sh: git not available, keeping existing gitinfo.tex" >&2
    exit 0
fi

# Short commit hash, with "-dirty" suffix if there are uncommitted changes
HASH=$(git describe --always --dirty --abbrev=7 --match=NOTHING)

# Tag on HEAD; otherwise distance from the last tag (e.g. ver-0.9.10-3-g86e0c52)
TAG=$(git describe --tags --exact-match --dirty 2>/dev/null \
      || git describe --tags --dirty 2>/dev/null \
      || echo "none")

# Commit date in YYYY-MM-DD format
DATE=$(git show -s --format=%cd --date=format:'%Y-%m-%d' HEAD)

NEW="% Auto-generated by gitinfo.sh -- do not edit, not tracked by git
\\newcommand{\\githash}{$HASH}
\\newcommand{\\gittag}{$TAG}
\\newcommand{\\gitdate}{$DATE}"

# Rewrite only if changed
if [ "$NEW" != "$(cat gitinfo.tex 2>/dev/null)" ]; then
    printf '%s\n' "$NEW" > gitinfo.tex
fi
